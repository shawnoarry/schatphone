  if (![MAP_PLACE_MEDIA_SLOT.HERO, MAP_PLACE_MEDIA_SLOT.DETAIL_GALLERY].includes(record.slot)) {
    continue
  }
  const key = `${record.mapPackId}:${record.placeId}`
  const gallery = mediaGalleryByPlaceKey.get(key) || []
