const createLegacySchemaReconciliationReader = (legacySchemaVersions = []) => {
  const acceptedVersions = new Set(legacySchemaVersions.map(Number))
  return ({ version, data } = {}) =>
    acceptedVersions.has(Number(version)) &&
    data &&
    typeof data === 'object' &&
    !Array.isArray(data)
      ? data
      : null
}

