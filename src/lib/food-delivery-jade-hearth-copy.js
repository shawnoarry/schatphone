const JADE_HEARTH_DISH_NUMBER_BY_ID = Object.freeze(
  Object.keys(JADE_HEARTH_MENU_COPY_BY_ID).reduce((numbers, itemId, index) => {
    numbers[itemId] = String(index + 1).padStart(2, '0')
    return numbers
  }, {}),
)

const languageBase = (language = 'zh-CN') =>
  String(language || '')
    .trim()
    .toLowerCase()
    .startsWith('en')
    ? 'en'
    : 'zh'

const localizedValue = (copy = {}, language = 'zh-CN') =>
  languageBase(language) === 'en' ? copy.en || copy.zh || '' : copy.zh || copy.en || ''

const resolveStandardField = (currentValue, fieldCopy, language) => {
  const current = typeof currentValue === 'string' ? currentValue : ''
  if (!fieldCopy || ![fieldCopy.zh, fieldCopy.en].includes(current)) return current
  return localizedValue(fieldCopy, language)
}

export const resolveJadeHearthMenuItemCopy = (item = {}, language = 'zh-CN') => {
  const copy = JADE_HEARTH_MENU_COPY_BY_ID[item?.id]
  if (!copy) return item
  const image = item.image || {}
  return {
    ...item,
    title: resolveStandardField(item.title, copy.title, language),
    desc: resolveStandardField(item.desc, copy.desc, language),
    ingredients: resolveStandardField(item.ingredients, copy.ingredients, language),
    image: {
      ...image,
      alt: resolveStandardField(image.alt, copy.imageAlt, language),
    },
  }
}

export const resolveJadeHearthOrderItemTitle = (item = {}, language = 'zh-CN') => {
  const copy = JADE_HEARTH_MENU_COPY_BY_ID[item?.menuItemId]
  if (!copy) return item?.title || ''
  return resolveStandardField(item.title, copy.title, language)
}

export const getJadeHearthMenuSearchValues = (item = {}) => {
  const copy = JADE_HEARTH_MENU_COPY_BY_ID[item?.id]
  const values = [item.title, item.desc, item.ingredients]
  if (copy) {
    for (const field of ['title', 'desc', 'ingredients']) {
      values.push(copy[field]?.zh, copy[field]?.en)
    }
  }
  return [...new Set(values.filter(Boolean).map((value) => String(value)))]
}

export const resolveJadeHearthDishNumber = (item = {}) =>
  JADE_HEARTH_DISH_NUMBER_BY_ID[item?.id] || '席'
